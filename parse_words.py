# パースと統合
words = {}

# Part 1 (英単語, 意味, 優先度, 例文)
for line in data_part1.strip().split("\n"):
    parts = line.split("\t")
    if len(parts) >= 2:
        en = parts[0].strip()
        ja = parts[1].strip()
        kana = kana_map.get(en, "")
        words[en.lower()] = {
            "en": en,
            "kana": f"（{kana}）" if kana else "",
            "ja": ja
        }

# Part 2 (英単語, 読み, 意味/例文)
for line in data_part2.strip().split("\n"):
    parts = line.split("\t")
    if len(parts) >= 3:
        en = parts[0].strip()
        kana = parts[1].strip()
        ja_raw = parts[2].strip()
        # have line might be '持っている、I have a dog. ...'
        if "、I have" in ja_raw:
            ja = "持っている、飼っている"
        else:
            ja = ja_raw
        
        key = en.lower()
        if key in words:
            # すでに存在する場合は読みを更新、意味を補強
            if not words[key]["kana"] and kana:
                words[key]["kana"] = f"（{kana}）"
            # 意味の調整（より充実している方を採用）
            if len(ja) > len(words[key]["ja"]):
                words[key]["ja"] = ja
        else:
            words[key] = {
                "en": en,
                "kana": f"（{kana}）" if kana else "",
                "ja": ja
            }

import json
